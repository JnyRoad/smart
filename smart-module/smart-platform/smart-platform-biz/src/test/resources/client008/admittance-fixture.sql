-- 仅供规格008独立Oracle测试：现有平台入厂表的合成字段基线，不是生产迁移。
CREATE TABLE SMT_ADMITTANCE_APPLY (
 ID NUMBER(19,0) PRIMARY KEY, PARK_ID NUMBER(10,0), VISITOR_NAME VARCHAR2(100 CHAR),
 VISITOR_PHOTO_ID VARCHAR2(128 CHAR), VISITOR_PHONE VARCHAR2(50 CHAR), CERT_NO VARCHAR2(100 CHAR),
 STATUS NUMBER(10,0), START_TIME TIMESTAMP, END_TIME TIMESTAMP,
 RECEPTIONIST_BADGE VARCHAR2(100 CHAR), RECEPTIONIST_NAME VARCHAR2(100 CHAR),
 RECEPTIONIST_PHONE VARCHAR2(50 CHAR), IS_SEND NUMBER(10,0), CREATE_TIME TIMESTAMP,
 REMARK VARCHAR2(1000 CHAR), SMS_CODE VARCHAR2(50 CHAR), COMPANY VARCHAR2(200 CHAR),
 PERSON_TYPE NUMBER(10,0), CAUSE NUMBER(10,0), THING NUMBER(10,0), PROCESS_ID VARCHAR2(100 CHAR),
 DEVICE_STATUS NUMBER(10,0), IS_VEHICLE NUMBER(10,0), UNION_ID VARCHAR2(128 CHAR),
 PERMIT_FACTORY_TYPE VARCHAR2(100 CHAR), AREA_TYPE VARCHAR2(100 CHAR),
 PERMIT_AREA VARCHAR2(1000 CHAR), PERMIT_OLD_AREA VARCHAR2(1000 CHAR), APPLY_TYPE NUMBER(10,0),
 ISC_SUBMIT_BATCH NUMBER(19,0)
);
CREATE TABLE SMT_ADMITTANCE_FELLOW (
 ID NUMBER(19,0) PRIMARY KEY, VISITOR_ID NUMBER(19,0), FELLOW_NAME VARCHAR2(100 CHAR),
 FELLOW_PHOTO_ID VARCHAR2(128 CHAR), CERT_NO VARCHAR2(100 CHAR), CERT_TYPE NUMBER(10,0),
 FRONT_PHOTO_ID VARCHAR2(128 CHAR), NATIVE_PLACE VARCHAR2(200 CHAR), IS_MAIN NUMBER(10,0)
);
