	@Transactional
	public void addRoomInfo(String badge,String floor,String roomName,String bedNum,String inTime){
		if(badge.equals("#")){
			return;
		}
		//查询是否入住
		int count = smtDormitoryStaffService.count(new LambdaQueryWrapper<SmtDormitoryStaff>()
				.eq(SmtDormitoryStaff::getStaffBadge, badge)
		);
		if(count > 0){
			//已入住
			log.error("{}已入住",badge);
			return;
		}
		//查询房间信息
		SmtDormitoryRoom dormitoryRoom = smtDormitoryRoomService.getOne(new LambdaQueryWrapper<SmtDormitoryRoom>()
				.eq(SmtDormitoryRoom::getRoomName, roomName)
		);
		//查询楼栋信息
		SmtDormitory smtDormitory = smtDormitoryService.getById(dormitoryRoom.getDormitoryId());
		//查询楼层信息
		SmtDormitoryFloor dormitoryFloor = smtDormitoryFloorService.getById(dormitoryRoom.getFloorId());
		//查询床位信息
		SmtDormitoryBed dormitoryBed = smtDormitoryBedService.getOne(new LambdaQueryWrapper<SmtDormitoryBed>()
				.eq(SmtDormitoryBed::getRoomId, dormitoryRoom.getId())
				.eq(SmtDormitoryBed::getBedNumber, Integer.parseInt(bedNum))
		);

		//获取员工信息
		SmtStaff staff = smtStaffService.getOne(new LambdaQueryWrapper<SmtStaff>().eq(SmtStaff::getBadge, badge));

		SmtDormitoryStaff dormitoryStaff = new SmtDormitoryStaff();
		dormitoryStaff.setStaffBadge(badge);
		dormitoryStaff.setStaffName(badge);
		if(null != staff){
			dormitoryStaff.setStaffName(staff.getName());
			dormitoryStaff.setStaffId(staff.getId());
			dormitoryStaff.setCompName(staff.getCompName());
			dormitoryStaff.setDepName(staff.getDepName());
			dormitoryStaff.setJobName(staff.getJobName());
			dormitoryStaff.setIsStaff(1);
		}
		if(!"#".equals(inTime)) {
			try {
				SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy/MM/dd");
				Date inDate = dateFormat.parse(inTime);
				dormitoryStaff.setCreateTime(inDate);
			} catch (Exception e) {
			}
		} else {
			dormitoryStaff.setCreateTime(new Date());
		}

		dormitoryStaff.setParkId(161);
		dormitoryStaff.setParkName("裕同科技石岩园区");
		dormitoryStaff.setDormitoryId(dormitoryRoom.getDormitoryId());
		dormitoryStaff.setDormitoryName(smtDormitory.getDormitoryName());
		dormitoryStaff.setFloorId(dormitoryRoom.getFloorId());
		dormitoryStaff.setFloorName(dormitoryFloor.getFloorName());
		dormitoryStaff.setRoomId(dormitoryRoom.getId());
		dormitoryStaff.setRoomName(dormitoryRoom.getRoomName());
		dormitoryStaff.setBedId(dormitoryBed.getId());
		dormitoryStaff.setBedNumber(dormitoryBed.getBedNumber());
		dormitoryStaff.setDormitoryTypeId(5000084);
		dormitoryStaff.setDormitoryTypeName("普工八人间");
		dormitoryStaff.setStaffSex(dormitoryRoom.getRoomSex());

		//写入数据
		smtDormitoryStaffService.save(dormitoryStaff);
	}


