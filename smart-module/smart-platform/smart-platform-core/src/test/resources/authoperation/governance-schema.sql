CREATE TABLE SMT_AUTH_GOVERNANCE_ACTION (
    ID NUMBER(19) NOT NULL,
    IDEMPOTENCY_KEY VARCHAR2(128 CHAR) NOT NULL,
    SUBJECT_KEY VARCHAR2(256 CHAR) NOT NULL,
    TARGET_ID NUMBER(19) NOT NULL,
    ACTION_TYPE VARCHAR2(32 CHAR) NOT NULL,
    ACTOR_USER_ID NUMBER(10) NOT NULL,
    ACTOR_USERNAME VARCHAR2(128 CHAR) NOT NULL,
    REASON_TEXT VARCHAR2(512 CHAR) NOT NULL,
    EXPECTED_OPERATION_VERSION NUMBER(19) NOT NULL,
    EXPECTED_STATE VARCHAR2(32 CHAR) NOT NULL,
    EXPECTED_ATTEMPT_ID NUMBER(19) NOT NULL,
    EXPECTED_ATTEMPT_NO NUMBER(10),
    OBSERVED_CONCLUSION VARCHAR2(32 CHAR),
    BEFORE_STATE VARCHAR2(32 CHAR) NOT NULL,
    AFTER_STATE VARCHAR2(32 CHAR) NOT NULL,
    REQUEST_FINGERPRINT CHAR(64 CHAR) NOT NULL,
    RESULT VARCHAR2(64 CHAR) NOT NULL,
    RESULT_CODE VARCHAR2(64 CHAR) NOT NULL,
    EVIDENCE_TYPE VARCHAR2(64 CHAR),
    EVIDENCE_REFERENCE VARCHAR2(256 CHAR),
    EVIDENCE_BODY CLOB,
    EVIDENCE_SHA256 CHAR(64 CHAR),
    OBSERVED_AT TIMESTAMP(6),
    CREATE_TIME TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_AUTH_GOV_ACTION PRIMARY KEY (TARGET_ID, ID),
    CONSTRAINT FK_AUTH_GOV_ACTION_TARGET FOREIGN KEY (TARGET_ID) REFERENCES SMT_AUTH_OPERATION_TARGET(ID),
    CONSTRAINT UK_AUTH_GOV_ACTION_KEY UNIQUE (ACTOR_USER_ID, IDEMPOTENCY_KEY, SUBJECT_KEY),
    CONSTRAINT CK_AUTH_GOV_ACTION_TYPE CHECK (ACTION_TYPE IN ('RETRY','MANUAL_VERIFICATION')),
    CONSTRAINT CK_AUTH_GOV_ACTION_CONCLUSION CHECK
        (OBSERVED_CONCLUSION IS NULL OR OBSERVED_CONCLUSION IN ('PERMISSION_ABSENT','PERMISSION_PRESENT','INCONCLUSIVE'))
);
