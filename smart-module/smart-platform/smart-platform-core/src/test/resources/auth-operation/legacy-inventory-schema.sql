-- 仅用于本任务合成 Oracle；两表只保存盘点事实与扫描控制，不代表生产迁移已批准。

CREATE TABLE SMT_AUTH_LEGACY_SCAN_FLOW (
    ID NUMBER(19) NOT NULL,
    RUN_ID VARCHAR2(64 CHAR) NOT NULL,
    FLOW_KIND VARCHAR2(24 CHAR) NOT NULL,
    REQUESTED_BY VARCHAR2(128 CHAR) NOT NULL,
    SCOPE_FINGERPRINT VARCHAR2(64 CHAR) NOT NULL,
    AUDIT_TICKET VARCHAR2(128 CHAR),
    CAPTURE_CUTOFF TIMESTAMP(6) NOT NULL,
    ID_HIGH_WATER NUMBER(19) NOT NULL,
    ID_LAST_ID NUMBER(19) NOT NULL,
    UPDATE_HIGH_WATER_AT TIMESTAMP(6),
    UPDATE_LAST_AT TIMESTAMP(6),
    UPDATE_LAST_ID NUMBER(19) NOT NULL,
    REVISIT_REQUIRED CHAR(1 CHAR) NOT NULL,
    REVISIT_HIGH_WATER_ID NUMBER(19),
    REVISIT_LAST_ID NUMBER(19) NOT NULL,
    ACTIVE_PASS VARCHAR2(16 CHAR) NOT NULL,
    ID_PASS_DONE CHAR(1 CHAR) NOT NULL,
    UPDATE_PASS_DONE CHAR(1 CHAR) NOT NULL,
    REVISIT_PASS_DONE CHAR(1 CHAR) NOT NULL,
    PAGE_SIZE NUMBER(3) NOT NULL,
    LEASE_OWNER VARCHAR2(128 CHAR),
    LEASE_TOKEN VARCHAR2(128 CHAR),
    LEASE_UNTIL TIMESTAMP(6),
    ROW_VERSION NUMBER(19) NOT NULL,
    FLOW_STATE VARCHAR2(16 CHAR) NOT NULL,
    LAST_ERROR_CODE VARCHAR2(64 CHAR),
    LAST_ERROR_DETAIL VARCHAR2(1000 CHAR),
    LAST_COMMIT_AT TIMESTAMP(6),
    CREATED_AT TIMESTAMP(6) NOT NULL,
    UPDATED_AT TIMESTAMP(6) NOT NULL,
    COMPLETED_AT TIMESTAMP(6),
    CONSTRAINT PK_AUTH_LEGACY_FLOW PRIMARY KEY (ID),
    CONSTRAINT UK_AUTH_LEGACY_FLOW_RUN UNIQUE (RUN_ID,FLOW_KIND),
    CONSTRAINT CK_AUTH_LEG_FLOW_KIND CHECK (FLOW_KIND IN ('CURRENT_SOURCE','ISC_TASK','ISC_DOWN','DIRECT_TASK','DIRECT_DOWN')),
    CONSTRAINT CK_AUTH_LEG_FLOW_PAGE CHECK (PAGE_SIZE BETWEEN 1 AND 200),
    CONSTRAINT CK_AUTH_LEG_FLOW_FLAGS CHECK (ID_PASS_DONE IN ('Y','N') AND UPDATE_PASS_DONE IN ('Y','N') AND REVISIT_PASS_DONE IN ('Y','N')),
    CONSTRAINT CK_AUTH_LEG_FLOW_REVISIT CHECK (REVISIT_REQUIRED IN ('Y','N')),
    CONSTRAINT CK_AUTH_LEG_FLOW_PASS CHECK (ACTIVE_PASS IN ('ID','UPDATE','REVISIT')),
    CONSTRAINT CK_AUTH_LEG_FLOW_STATE CHECK (FLOW_STATE IN ('READY','RUNNING','COMPLETE','ERROR'))
);

CREATE UNIQUE INDEX UK_AUTH_LEGACY_ACTIVE_FLOW ON SMT_AUTH_LEGACY_SCAN_FLOW
    (CASE WHEN FLOW_STATE IN ('READY','RUNNING','ERROR') THEN FLOW_KIND END);
CREATE INDEX IX_AUTH_LEGACY_FLOW_CLAIM ON SMT_AUTH_LEGACY_SCAN_FLOW (FLOW_STATE,LEASE_UNTIL,ID);

CREATE TABLE SMT_AUTH_LEGACY_REVIEW (
    ID NUMBER(19) NOT NULL,
    RUN_FLOW_ID NUMBER(19) NOT NULL,
    FLOW_KIND VARCHAR2(24 CHAR) NOT NULL,
    ROW_KIND VARCHAR2(24 CHAR) NOT NULL,
    SOURCE_TABLE VARCHAR2(64 CHAR) NOT NULL,
    SOURCE_ROW_ID VARCHAR2(128 CHAR) NOT NULL,
    LEGACY_REF VARCHAR2(192 CHAR) NOT NULL,
    REVISION_NO NUMBER(10) NOT NULL,
    RAW_COLUMN_SET_VERSION VARCHAR2(64 CHAR) NOT NULL,
    RAW_ROW_FORMAT VARCHAR2(32 CHAR) NOT NULL,
    RAW_ROW_PAYLOAD CLOB NOT NULL,
    RAW_ROW_SHA256 VARCHAR2(64 CHAR) NOT NULL,
    RAW_COMPLETE CHAR(1 CHAR) NOT NULL,
    RAW_COMPLETENESS_REASON VARCHAR2(256 CHAR),
    EVIDENCE_FORMAT VARCHAR2(32 CHAR) NOT NULL,
    EVIDENCE_PAYLOAD CLOB NOT NULL,
    EVIDENCE_SHA256 VARCHAR2(64 CHAR) NOT NULL,
    REVISION_FINGERPRINT VARCHAR2(64 CHAR) NOT NULL,
    CAPTURED_AT TIMESTAMP(6) NOT NULL,
    PARK_ID NUMBER(10),
    PARK_STATE VARCHAR2(16 CHAR) NOT NULL,
    DEVICE_CODE VARCHAR2(512 CHAR),
    DEVICE_TYPE NUMBER(10),
    ACCESS_TYPE VARCHAR2(16 CHAR),
    SERVICE_TYPE NUMBER(10),
    SERVICE_FAMILY VARCHAR2(32 CHAR),
    CARD_NO VARCHAR2(512 CHAR),
    STAFF_ID NUMBER(19),
    ISC_PERSON_ID VARCHAR2(512 CHAR),
    BADGE VARCHAR2(512 CHAR),
    IMAGE_ID VARCHAR2(512 CHAR),
    ACTION NUMBER(10),
    STATUS NUMBER(10),
    TASK_TYPE NUMBER(10),
    CODE NUMBER(10),
    RELATED_TASK_REF VARCHAR2(192 CHAR),
    EXTERNAL_TASK_ID VARCHAR2(512 CHAR),
    IDENTITY_STATE VARCHAR2(16 CHAR) NOT NULL,
    RESIDUE_KIND VARCHAR2(24 CHAR) NOT NULL,
    REVIEW_STATE VARCHAR2(24 CHAR) NOT NULL,
    REVIEW_REASON VARCHAR2(1000 CHAR) NOT NULL,
    PHYSICAL_STATE VARCHAR2(16 CHAR) NOT NULL,
    FIRST_SEEN_AT TIMESTAMP(6) NOT NULL,
    LAST_SEEN_AT TIMESTAMP(6) NOT NULL,
    ROW_VERSION NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP(6) NOT NULL,
    UPDATED_AT TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_AUTH_LEGACY_REVIEW PRIMARY KEY (ID),
    CONSTRAINT FK_AUTH_LEG_REVIEW_FLOW FOREIGN KEY (RUN_FLOW_ID) REFERENCES SMT_AUTH_LEGACY_SCAN_FLOW(ID),
    CONSTRAINT UK_AUTH_LEG_REVIEW_REV UNIQUE (LEGACY_REF,REVISION_NO),
    CONSTRAINT UK_AUTH_LEG_REVIEW_FP UNIQUE (LEGACY_REF,REVISION_FINGERPRINT),
    CONSTRAINT CK_AUTH_LEG_REVIEW_FLOW CHECK (FLOW_KIND IN ('CURRENT_SOURCE','ISC_TASK','ISC_DOWN','DIRECT_TASK','DIRECT_DOWN')),
    CONSTRAINT CK_AUTH_LEG_REVIEW_ROW CHECK (ROW_KIND IN ('SOURCE_BASELINE','TASK','DOWN_RECORD')),
    CONSTRAINT CK_AUTH_LEG_REVIEW_RAW CHECK (RAW_COMPLETE IN ('Y','N')),
    CONSTRAINT CK_AUTH_LEG_REVIEW_PARK CHECK (PARK_STATE IN ('KNOWN','UNKNOWN','CONFLICT')),
    CONSTRAINT CK_AUTH_LEG_REVIEW_IDENT CHECK (IDENTITY_STATE IN ('UNIQUE','UNKNOWN','AMBIGUOUS')),
    CONSTRAINT CK_AUTH_LEG_REVIEW_STATE CHECK (REVIEW_STATE IN ('DISCOVERED','REVIEW_REQUIRED')),
    CONSTRAINT CK_AUTH_LEG_REVIEW_PHYS CHECK (PHYSICAL_STATE='UNKNOWN')
);

CREATE INDEX IX_AUTH_LEGACY_REVIEW_PARK ON SMT_AUTH_LEGACY_REVIEW (PARK_ID,REVIEW_STATE,ID);
CREATE INDEX IX_AUTH_LEGACY_REVIEW_EXC ON SMT_AUTH_LEGACY_REVIEW (PARK_STATE,REVIEW_STATE,ID);
CREATE INDEX IX_AUTH_LEGACY_REVIEW_FLOW ON SMT_AUTH_LEGACY_REVIEW (FLOW_KIND,ID);
