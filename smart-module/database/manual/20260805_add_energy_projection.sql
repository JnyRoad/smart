-- 能耗日汇总投影表。
-- 本脚本仅创建不存在的对象；若目标表已存在，部署前应由 DBA 核对其字段和约束是否符合本脚本。
-- 重复入队由后续服务先尝试唯一键去重插入，再仅对已存在行更新队列状态，避免并发首次入队产生重复主键。
-- 回滚仅删除被本发行 marker 明确记录为新建的表，marker 表作为审计记录永久保留。

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'SMT_ENERGY_RELEASE_MARKER';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE SMT_ENERGY_RELEASE_MARKER (
                RELEASE_KEY VARCHAR2(64) NOT NULL,
                OBJECT_NAME VARCHAR2(30) NOT NULL,
                OBJECT_TYPE VARCHAR2(16) NOT NULL,
                CREATED_AT TIMESTAMP(6) NOT NULL,
                ROLLED_BACK_AT TIMESTAMP(6),
                CONSTRAINT PK_SMT_ENERGY_REL_MARKER PRIMARY KEY (RELEASE_KEY, OBJECT_NAME, OBJECT_TYPE)
            )
        ]';
    END IF;
END;
