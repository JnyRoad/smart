-- 兼容本发行早期已建表但尚未含租约令牌的环境；列存在时不重复执行 ALTER。
DECLARE
    v_table_count NUMBER;
    v_column_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_table_count FROM USER_TABLES WHERE TABLE_NAME = 'SMT_ENERGY_PROJECTION_QUEUE';
    IF v_table_count = 1 THEN
        SELECT COUNT(*) INTO v_column_count FROM USER_TAB_COLUMNS
            WHERE TABLE_NAME = 'SMT_ENERGY_PROJECTION_QUEUE' AND COLUMN_NAME = 'LEASE_TOKEN';
        IF v_column_count = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE SMT_ENERGY_PROJECTION_QUEUE ADD (LEASE_TOKEN VARCHAR2(64))'; END IF;
        SELECT COUNT(*) INTO v_column_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'SMT_ENERGY_PROJECTION_QUEUE' AND COLUMN_NAME = 'RETRY_COUNT';
        IF v_column_count = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE SMT_ENERGY_PROJECTION_QUEUE ADD (RETRY_COUNT NUMBER(10) DEFAULT 0 NOT NULL)'; END IF;
        SELECT COUNT(*) INTO v_column_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'SMT_ENERGY_PROJECTION_QUEUE' AND COLUMN_NAME = 'NEXT_RETRY_AT';
        IF v_column_count = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE SMT_ENERGY_PROJECTION_QUEUE ADD (NEXT_RETRY_AT TIMESTAMP(6))'; END IF;
    END IF;
END;
